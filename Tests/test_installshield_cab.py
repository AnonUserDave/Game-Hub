    def test_path_traversal_is_refused(self):
        b = CabBuilder()
        evil = b.add_directory("..\\..\\escape")
        b.add_file("owned.txt", b"x", directory=evil)
        b.add_file("a\\b.txt", b"y")
        b.add_group("G", 0, 1)
        b.build(self.tmp / "cabs")
        out = self.tmp / "out"
        with Cabinet.from_directory(self.tmp / "cabs") as cab:
            for name in ("owned.txt", 1):
                with self.assertRaises(CabinetError):
                    cab.extract(name, out)
            for layout in isc.LAYOUTS:
                with self.assertRaises(CabinetError):
                    cab.extract_all(out, layout=layout)
        self.assertFalse((self.tmp / "escape").exists())
        self.assertEqual([p for p in out.rglob("*") if p.is_file()], [])

