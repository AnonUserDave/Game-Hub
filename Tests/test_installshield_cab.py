def obfuscate(data: bytes, seed: int = 0) -> bytes:
    """Inverse of the documented transform, written independently per byte."""
    out = bytearray()
    for i, value in enumerate(data):
        value = (value + (seed + i) % 0x47) & 0xFF
        value = ((value << 2) | (value >> 6)) & 0xFF
        out.append(value ^ 0xD5)
    return bytes(out)


def reference_deobfuscate(data: bytes, seed: int = 0) -> bytes:
    out = bytearray()
    for i, value in enumerate(data):
        value ^= 0xD5
        value = ((value >> 2) | (value << 6)) & 0xFF
        out.append((value - (seed + i) % 0x47) & 0xFF)
    return bytes(out)


class CabBuilder:
    """Builds a tiny InstallShield cabinet set (v5, v6 or unicode v17 layout)."""

    DATA_START = 0x200

    def __init__(self, major=6):
        self.major = major
        self.directories = [""]
        self.files = []
        self.groups = []
        self.components = []

    def add_directory(self, name):
        self.directories.append(name)
        return len(self.directories) - 1

    def add_file(self, name, data, directory=0, compress=True, obfuscated=False, chunk=1024,
                 invalid=False, link_previous=None, bad_md5=False):
        self.files.append(dict(name=name, data=data, directory=directory, compress=compress,
                               obfuscated=obfuscated, chunk=chunk, invalid=invalid,
                               link_previous=link_previous, bad_md5=bad_md5))
        return len(self.files) - 1

    def add_group(self, name, first, last):
        self.groups.append((name, first, last))

    def add_component(self, name, group_names):
        self.components.append((name, group_names))

    # ---- helpers ---------------------------------------------------------
    def _text(self, value):
        if self.major >= 17:
            return value.encode("utf-16-le") + b"\0\0"
        return value.encode("cp1252") + b"\0"

    @staticmethod
    def _stored(spec):
        data = spec["data"]
        if spec["compress"]:
            stored = bytearray()
            for start in range(0, len(data), spec["chunk"]):
                packer = zlib.compressobj(9, zlib.DEFLATED, -15)
                payload = packer.compress(data[start:start + spec["chunk"]]) + packer.flush()
                stored += struct.pack("<H", len(payload)) + payload
            stored = bytes(stored)
        else:
            stored = data
        return obfuscate(stored) if spec["obfuscated"] else stored

    def _version(self):
        if self.major >= 17:
            return 0x04000000 | (self.major * 100)
        return 0x01000000 | (self.major << 12) | 0x00C

    # ---- build -----------------------------------------------------------
    def build(self, directory, capacity=None, embedded=False):
        """Write data1.hdr (unless embedded) and dataN.cab files; return the dir."""
        directory = Path(directory)
        directory.mkdir(parents=True, exist_ok=True)
        records = []
        volumes = [bytearray()]
        for index, spec in enumerate(self.files):
            record = dict(flags=0, segments=[], size=len(spec["data"]),
                          md5=hashlib.md5(spec["data"]).digest(), link_flags=0, link_previous=0)
            if spec["compress"]:
                record["flags"] |= isc.FILE_COMPRESSED
            if spec["obfuscated"]:
                record["flags"] |= isc.FILE_OBFUSCATED
            if spec["bad_md5"]:
                record["md5"] = bytes(16)
            records.append(record)
            if spec["invalid"]:
                record["flags"] |= isc.FILE_INVALID
                record["compressed"] = 0
                continue
            if spec["link_previous"] is not None:
                target = records[spec["link_previous"]]
                record.update(segments=target["segments"], compressed=target["compressed"],
                              link_flags=isc.LINK_PREV, link_previous=spec["link_previous"])
                target["link_flags"] |= isc.LINK_NEXT
                continue
            stored = self._stored(spec)
            record["compressed"] = len(stored) if spec["compress"] else len(spec["data"])
            position = 0
            while True:
                room = len(stored) - position if capacity is None else capacity - len(volumes[-1])
                if room <= 0 and len(stored) > position:
                    volumes.append(bytearray())
                    continue
                take = min(room, len(stored) - position)
                record["segments"].append((len(volumes), self.DATA_START + len(volumes[-1]), take))
                volumes[-1] += stored[position:position + take]
                position += take
                if position >= len(stored):
                    break
            if len(record["segments"]) > 1 and self.major >= 6:
                record["flags"] |= isc.FILE_SPLIT
        header = self._header(records)
        base = 0
        if embedded:
            assert len(volumes) == 1
            base = (len(header) + 0x1FF) // 0x200 * 0x200 - self.DATA_START
            for record in records:
                record["segments"] = [(v, o + base, n) for v, o, n in record["segments"]]
            header = self._header(records)
        else:
            (directory / "data1.hdr").write_bytes(header)
        for number, payload in enumerate(volumes, 1):
            vh = self._volume_header(number, records, base)
            if embedded:
                blob = bytearray(header)
                blob[20:20 + len(vh)] = vh
                blob += bytes(self.DATA_START + base - len(blob))
            else:
                blob = bytearray(struct.pack("<4sIIII", b"ISc(", self._version(), 0, 0, 0))
                blob += vh
                blob += bytes(self.DATA_START - len(blob))
            (directory / f"DATA{number}.CAB").write_bytes(bytes(blob + payload))
        return directory

    def _volume_header(self, number, records, base):
        present = [(i, r) for i, r in enumerate(records)
                   if not r["link_flags"] & isc.LINK_PREV
                   and any(v == number for v, _, _ in r["segments"])]
        fields = [0] * 8
        if present:
            first_index, first = present[0]
            last_index, last = present[-1]
            seg_first = next(s for s in first["segments"] if s[0] == number)
            seg_last = next(s for s in last["segments"] if s[0] == number)

            def sizes(record, segment):
                whole = len(record["segments"]) == 1
                expanded = record["size"] if whole else (0 if record["flags"] & isc.FILE_COMPRESSED
                                                          else segment[2])
                return segment[1], expanded, segment[2]

            fields = [first_index, last_index, *sizes(first, seg_first), *sizes(last, seg_last)]
        data_offset = self.DATA_START + base
        if self.major <= 5:
            return struct.pack("<10I", data_offset, 0, *fields)
        return struct.pack("<QIIQQQQQQ", data_offset, *fields)

    def _header(self, records):
        area = bytearray(isc.CAB_DESCRIPTOR_FIXED + 8 * isc.HASH_BUCKETS)

        def alloc(blob):
            while len(area) % 4:
                area.append(0)
            offset = len(area)
            area.extend(blob)
            return offset

        heads = [0] * isc.HASH_BUCKETS
        group_skip = 0x48 if self.major <= 5 else 0x12
        for number, (name, first, last) in enumerate(self.groups):
            name_offset = alloc(self._text(name))
            desc = alloc(struct.pack("<I", name_offset) + bytes(group_skip)
                         + struct.pack("<II", first, last))
            bucket = number % 3     # several groups share a bucket: exercise chaining
            heads[bucket] = alloc(struct.pack("<III", name_offset, desc, heads[bucket]))
        component_heads = [0] * isc.HASH_BUCKETS
        component_skip = 0x6C if self.major <= 5 else 0x6B
        for number, (name, group_names) in enumerate(self.components):
            name_offset = alloc(self._text(name))
            table = alloc(b"".join(struct.pack("<I", alloc(self._text(g))) for g in group_names))
            desc = alloc(struct.pack("<I", name_offset) + bytes(component_skip)
                         + struct.pack("<HI", len(group_names), table))
            bucket = 5 + number
            component_heads[bucket] = alloc(struct.pack("<III", name_offset, desc, 0))
        struct.pack_into(f"<{isc.HASH_BUCKETS}I", area, isc.CAB_DESCRIPTOR_FIXED, *heads)
        struct.pack_into(f"<{isc.HASH_BUCKETS}I", area,
                         isc.CAB_DESCRIPTOR_FIXED + 4 * isc.HASH_BUCKETS, *component_heads)
        while len(area) % 4:
            area.append(0)
        descriptor_size = table_offset = len(area)

        dirs, count = len(self.directories), len(self.files)
        entries = dirs + (count if self.major <= 5 else 0)
        table = bytearray(4 * entries)
        descriptor_base = len(table)
        record_size = 0x3A if self.major <= 5 else 0x57
        table += bytes(record_size * count)

        def text(value):
            offset = len(table)
            table.extend(self._text(value))
            return offset

        for i, name in enumerate(self.directories):
            struct.pack_into("<I", table, 4 * i, text(name))
        for i, (spec, record) in enumerate(zip(self.files, records)):
            name_offset = text(spec["name"])
            segments = record["segments"]
            volume, data_offset = (segments[0][0], segments[0][1]) if segments else (0, 0)
            offset = descriptor_base + i * record_size
            if self.major <= 5:
                struct.pack_into("<I", table, 4 * (dirs + i), offset)
                struct.pack_into("<IIHII20sI16s", table, offset, name_offset, spec["directory"],
                                 record["flags"], record["size"], record["compressed"], b"",
                                 data_offset, record["md5"])
            else:
                struct.pack_into("<HQQQ16s16sIH12sIIBH", table, offset, record["flags"],
                                 record["size"], record["compressed"], data_offset,
                                 record["md5"], b"", name_offset, spec["directory"], b"",
                                 record["link_previous"], 0, record["link_flags"], volume)
        struct.pack_into("<I", area, 0x0C, table_offset)
        struct.pack_into("<II", area, 0x14, len(table), len(table))
        struct.pack_into("<I", area, 0x1C, dirs)
        struct.pack_into("<II", area, 0x28, count, descriptor_base if self.major > 5 else 0)
        common = struct.pack("<4sIIII", b"ISc(", self._version(), 0, 0x200, descriptor_size)
        return bytes(common + bytes(0x200 - len(common)) + area + table)


def noise(size, seed):
    return random.Random(seed).randbytes(size)


def text_blob(size, seed):
    words = [b"tee", b"green", b"fairway", b"bunker", b"rough", b"\r\n"]
    rng = random.Random(seed)
    return b" ".join(rng.choice(words) for _ in range(size))[:size]


class SyntheticCabinetTests(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.tmp = Path(self._tmp.name)

    def tearDown(self):
        self._tmp.cleanup()

    def standard(self, major=6, capacity=3000):
        b = CabBuilder(major)
        sub = b.add_directory("Sub Dir\\[x]")
        b.add_file("small.txt", b"hello golf\n")
        b.add_file("big noise.bin", noise(12000, 1), directory=sub, chunk=1024)
        b.add_file("plain.dat", text_blob(5000, 2), directory=sub, compress=False)
        b.add_file("secret.cfg", text_blob(7000, 3), obfuscated=True, chunk=2048)
        b.add_file("raw-secret.bin", noise(4100, 4), compress=False, obfuscated=True)
        b.add_file("empty.txt", b"")
        b.add_file("tail.txt", b"last file\n")
        b.add_group("My Group <1>", 0, 2)
        b.add_group("Second", 3, 4)
        b.add_group("Third", 5, 6)
        b.add_component("<Data>\\Main", ["My Group <1>", "Second"])
        b.build(self.tmp / "cabs", capacity=capacity)
        return b

    def test_listing_and_metadata(self):
        builder = self.standard()
        with Cabinet.from_directory(self.tmp / "cabs") as cab:
            self.assertEqual(cab.major_version, 6)
            self.assertTrue(cab.verifies_md5)
            self.assertEqual([g.name for g in cab.groups()], ["My Group <1>", "Second", "Third"])
            self.assertEqual(cab.components()[0].name, "<Data>\\Main")
            self.assertEqual(cab.components()[0].file_groups, ("My Group <1>", "Second"))
            self.assertEqual(cab.directories(), ["", "Sub Dir\\[x]"])
            entries = list(cab.files())
            self.assertEqual([e.name for e in entries], [f["name"] for f in builder.files])
            noisy = entries[1]
            self.assertEqual(noisy.path, "Sub Dir/[x]/big noise.bin")
            self.assertEqual(noisy.md5, hashlib.md5(noise(12000, 1)).hexdigest())
            self.assertTrue(noisy.split and noisy.compressed and noisy.volume == 1)
            self.assertEqual(str(noisy.relative_path()), "My_Group__1_/Sub_Dir/_x_/big noise.bin")
            self.assertEqual(str(noisy.relative_path("directory")), "Sub Dir/[x]/big noise.bin")

    def test_multi_volume_extract_is_byte_exact(self):
        builder = self.standard()
        self.assertGreaterEqual(len(list((self.tmp / "cabs").glob("DATA*.CAB"))), 6)
        out = self.tmp / "out"
        with Cabinet.from_directory(self.tmp / "cabs") as cab:
            written = cab.extract_all(out)
            self.assertEqual(len(written), len(builder.files))
            for spec, entry in zip(builder.files, cab.files()):
                path = out / entry.relative_path()
                self.assertEqual(path.read_bytes(), spec["data"], spec["name"])
                self.assertEqual(cab.read(entry), spec["data"])
        self.assertEqual(sorted(p.name for p in out.rglob(".*")), [])

    def test_chunks_are_bounded(self):
        b = CabBuilder()
        b.add_file("stored.bin", noise(isc.COPY_BLOCK + 10, 9), compress=False)
        b.add_file("packed.bin", bytes(300000), chunk=65536)
        b.add_group("G", 0, 1)
        b.build(self.tmp / "cabs", capacity=400000)
        with Cabinet.from_directory(self.tmp / "cabs") as cab:
            for entry in cab.files():
                sizes = [len(c) for c in cab.iter_chunks(entry)]
                self.assertEqual(sum(sizes), entry.size)
                self.assertLessEqual(max(sizes), isc.COPY_BLOCK)

    def test_version5_split_detection_without_flag(self):
        builder = self.standard(major=5)
        out = self.tmp / "out"
        with Cabinet.from_directory(self.tmp / "cabs") as cab:
            self.assertEqual(cab.major_version, 5)
            self.assertFalse(cab.verifies_md5)
            self.assertFalse(any(e.split for e in cab.files()))
            cab.extract_all(out)
            for spec, entry in zip(builder.files, cab.files()):
                self.assertEqual((out / entry.relative_path()).read_bytes(), spec["data"])

