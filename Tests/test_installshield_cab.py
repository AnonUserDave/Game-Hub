    def test_existing_output_is_verified_before_skip(self):
        self.standard()
        out = self.tmp / "out"
        with Cabinet.from_directory(self.tmp / "cabs") as cab:
            path = cab.extract("plain.dat", out)
            before = path.stat().st_mtime_ns
